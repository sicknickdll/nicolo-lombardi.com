#!/usr/bin/env python3
"""I see u: the eye tiles of the opening mosaic.

From each painting of js/isee/paintings.js, a square crop of one eye (the one nearer the viewer:
on a turned head, the one away from where it looks), all packed in one sprite,
assets/archive/isee/eyes.webp, a grid of COLS × TILE px tiles in the order of the paintings.
Writes js/isee/eyes.js with the sprite's layout. Run after export.py:

    python3 tools/isee/eyes.py [first id]
"""
import json
import math
import os
import sys

from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
TILE, COLS = 96, 20
src = open(os.path.join(ROOT, "js", "isee", "paintings.js")).read()
P = [json.loads(l.strip().rstrip(",")) for l in src.splitlines() if l.strip().startswith("{")]
rows = math.ceil(len(P) / COLS)
sheet = Image.new("RGB", (COLS * TILE, rows * TILE), "black")
for i, p in enumerate(P):
    im = Image.open(os.path.join(ROOT, p["src"].lstrip("/"))).convert("RGB")
    short = min(im.size)
    ipd = p["size"] * short
    cx = p["eye"][0] * im.width - math.copysign(ipd / 2, p["dir"][0] or 1)
    cy = p["eye"][1] * im.height
    side = max(ipd * 1.05, short * 0.04)
    box = (cx - side / 2, cy - side / 2, cx + side / 2, cy + side / 2)
    tile = im.crop(tuple(round(v) for v in box)).resize((TILE, TILE), Image.LANCZOS)
    sheet.paste(tile, ((i % COLS) * TILE, (i // COLS) * TILE))
sheet.save(os.path.join(ROOT, "assets", "archive", "isee", "eyes.webp"), "WEBP", quality=74, method=6)
first = P.index(next(p for p in P if p["id"] == sys.argv[1])) if len(sys.argv) > 1 else 0
with open(os.path.join(ROOT, "js", "isee", "eyes.js"), "w") as fh:
    fh.write(
        "// GENERATED by tools/isee/eyes.py: one eye of each painting, in a sprite (see the README).\n"
        f"export const EYES = {json.dumps({'src': '/assets/archive/isee/eyes.webp', 'tile': TILE, 'cols': COLS, 'count': len(P), 'first': first})};\n"
    )
print(len(P), "eyes,", os.path.getsize(os.path.join(ROOT, "assets", "archive", "isee", "eyes.webp")) // 1000, "KB")
