#!/usr/bin/env python3
"""I see u: the tiles of the opening mosaic, one pointing hand from each painting.

From each finger of js/isee/paintings.js, a square crop around the hand (the fingertip in front,
the knuckles behind), all packed in one sprite, assets/archive/isee/fingers.webp, a grid of
COLS × TILE px tiles in the order of the paintings. Writes js/isee/fingers.js with the sprite's
layout. Run after export.py:

    python3 tools/isee/fingers.py [first id]
"""
import json
import math
import os
import sys

from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
TILE, COLS = 96, 20
src = open(os.path.join(ROOT, "js", "isee", "paintings.js")).read()
P = [json.loads(l.strip().rstrip(",")) for l in src.splitlines() if l.strip().startswith("{")]
rows = math.ceil(len(P) / COLS)
sheet = Image.new("RGB", (COLS * TILE, rows * TILE), "black")
for i, p in enumerate(P):
    im = Image.open(os.path.join(ROOT, p["src"].lstrip("/"))).convert("RGB")
    short = min(im.size)
    f = p["size"] * short  # the finger, in image pixels
    # centred a little behind the tip, so the finger and the hand it comes from are both in
    cx = p["tip"][0] * im.width - p["dir"][0] * f * 0.55
    cy = p["tip"][1] * im.height - p["dir"][1] * f * 0.55
    side = max(f * 2.1, short * 0.05)
    box = (cx - side / 2, cy - side / 2, cx + side / 2, cy + side / 2)
    tile = im.crop(tuple(round(v) for v in box)).resize((TILE, TILE), Image.LANCZOS)
    sheet.paste(tile, ((i % COLS) * TILE, (i // COLS) * TILE))
sheet.save(os.path.join(ROOT, "assets", "archive", "isee", "fingers.webp"), "WEBP", quality=74, method=6)
first = P.index(next(p for p in P if p["id"] == sys.argv[1])) if len(sys.argv) > 1 else 0
with open(os.path.join(ROOT, "js", "isee", "fingers.js"), "w") as fh:
    fh.write(
        "// GENERATED by tools/isee/fingers.py: one pointing hand of each painting, in a sprite (see the README).\n"
        f"export const FINGERS = {json.dumps({'src': '/assets/archive/isee/fingers.webp', 'tile': TILE, 'cols': COLS, 'count': len(P), 'first': first})};\n"
    )
print(len(P), "hands,", os.path.getsize(os.path.join(ROOT, "assets", "archive", "isee", "fingers.webp")) // 1000, "KB")
