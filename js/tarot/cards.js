//   guideOpen                      her lines when it turns out to be the guiding card
//   lens                           Layer 3: how this card, as guiding card, colours the others.
//                                  side: which face of the other cards it brings forward ("light"/"shade");
//                                  one template per position, with {light} {shade} {Light} {Shade}
//                                  {name} {Name} for the drawn card; closing: her last observation.
//   axes                           Layer 4: where the card stands on six oppositions (see lines.js)
